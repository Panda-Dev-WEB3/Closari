// write:  contracts/out → src/abi/*.ts (+ index.ts)
// check:  fails if src/abi is stale or if any interface ABI differs from contracts/interfaces.lock.json
// freeze: rewrites contracts/interfaces.lock.json (only with an "Interface change" entry in the spec)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..", "..", "..");
const OUT = join(ROOT, "contracts", "out");
const ABI_DIR = join(import.meta.dir, "..", "src", "abi");
const LOCK = join(ROOT, "contracts", "interfaces.lock.json");

export const INTERFACES = [
  "IExchangeCalendar",
  "IStockTokenAllowList",
  "IMarketFactory",
  "ILMSRMarket",
  "ISettlementOracle",
  "IHousePool",
  "IFeeRouter",
  "IClsrStaking",
  "IStockToken",
  "IBeacon",
  "IUSDG",
] as const;
// Contracts whose ABIs are exported once they exist (added in Tasks 7–9).
export const CONTRACTS = ["ExchangeCalendar", "StockTokenAllowList", "MarketFactory"] as const;

type AbiItem = { type: string; name?: string; inputs?: { type: string }[] };

function readAbi(name: string): AbiItem[] | undefined {
  const p = join(OUT, `${name}.sol`, `${name}.json`);
  if (!existsSync(p)) return undefined;
  return JSON.parse(readFileSync(p, "utf8")).abi as AbiItem[];
}

function key(i: AbiItem): string {
  return `${i.type}:${i.name ?? ""}(${(i.inputs ?? []).map((x) => x.type).join(",")})`;
}

export function abiHash(abi: AbiItem[]): string {
  const sorted = [...abi].sort((a, b) => key(a).localeCompare(key(b)));
  const h = new Bun.CryptoHasher("sha256");
  h.update(JSON.stringify(sorted));
  return h.digest("hex");
}

/** Differences between the frozen lock and the current interface hashes, one message per interface. */
export function interfaceDrift(
  lock: Record<string, string>,
  hashes: Record<string, string>,
): string[] {
  const errors: string[] = [];
  for (const [name, hash] of Object.entries(hashes)) {
    if (!(name in lock)) errors.push(`${name} is missing from interfaces.lock.json`);
    else if (lock[name] !== hash)
      errors.push(`${name} differs from interfaces.lock.json (frozen interface changed)`);
  }
  for (const name of Object.keys(lock))
    if (!(name in hashes))
      errors.push(`${name} is in interfaces.lock.json but is not a frozen interface`);
  return errors;
}

function constName(name: string): string {
  return `${name[0]?.toLowerCase()}${name.slice(1)}Abi`;
}

function render(): Map<string, string> {
  const files = new Map<string, string>();
  const names: string[] = [];
  for (const name of [...INTERFACES, ...CONTRACTS]) {
    const abi = readAbi(name);
    if (!abi) {
      if ((INTERFACES as readonly string[]).includes(name))
        throw new Error(`missing ABI for ${name}; run forge build`);
      continue;
    }
    names.push(name);
    files.set(
      `${name}.ts`,
      `// Generated by packages/core/scripts/abi.ts from contracts/out. Do not edit.\nexport const ${constName(name)} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    );
  }
  files.set(
    "index.ts",
    `// Generated. Do not edit.\n${names.map((n) => `export { ${constName(n)} } from "./${n}.ts";`).join("\n")}\n`,
  );
  return files;
}

function interfaceHashes(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const name of INTERFACES) out[name] = abiHash(readAbi(name) ?? []);
  return out;
}

function main(): void {
  const mode = process.argv[2];
  if (mode === "write") {
    mkdirSync(ABI_DIR, { recursive: true });
    for (const [file, body] of render()) writeFileSync(join(ABI_DIR, file), body);
    console.log(`wrote ${render().size} files to src/abi`);
  } else if (mode === "freeze") {
    writeFileSync(LOCK, `${JSON.stringify(interfaceHashes(), null, 2)}\n`);
    console.log("wrote contracts/interfaces.lock.json");
  } else if (mode === "check") {
    const errors: string[] = [];
    const files = render();
    const existing = existsSync(ABI_DIR) ? readdirSync(ABI_DIR) : [];
    for (const [file, body] of files) {
      const p = join(ABI_DIR, file);
      if (!existsSync(p) || readFileSync(p, "utf8") !== body)
        errors.push(`src/abi/${file} is stale (run bun run abi:write)`);
    }
    for (const f of existing) if (!files.has(f)) errors.push(`src/abi/${f} has no source ABI`);
    const lock = JSON.parse(readFileSync(LOCK, "utf8")) as Record<string, string>;
    errors.push(...interfaceDrift(lock, interfaceHashes()));
    if (errors.length) {
      console.error(errors.join("\n"));
      process.exit(1);
    }
    console.log("ABIs current; interfaces match the freeze");
  } else {
    console.error("usage: abi.ts write|check|freeze");
    process.exit(2);
  }
}

if (import.meta.main) main();
